public class JavaVariables {
    public static void main(String[] args){
        print();
    }

    public static void print(){
        //This is a string data type which can store group of characters
        String name = "Abhinav";
        //This is an integer data type which can store numeric values
        int passCode = 6969;
        //This is a float datatype which stores decimal values to it
        float weight = 74.7F;
        //This is a character data type which can store a single character value
        char initial = 'a';
        //This is a boolean data type which can store only two things either true or false.
        boolean testCall = true;
        System.out.println("Name: "+name);
        System.out.println("PassCode: "+passCode);
        System.out.println("Weight: "+weight);
        System.out.println("Char: "+initial);
        System.out.println("testCall: "+testCall);
    }
}
