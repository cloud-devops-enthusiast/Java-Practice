public class JavaMath {
    public static void main(String[] args){
        //trying different math operators
        //Maximum Function
        System.out.println("Maximum Function, this lets you to find the greater one numeric value among the others. "+Math.max(2,5));
        //Minimum Function
        System.out.println("Minimum Function, this lets you to find the smaller one numeric value among the others. "+Math.min(2,5));
        //Square root Function
        System.out.println("Taking out square root of a number. "+Math.sqrt(16));
        //Absolute Function
        System.out.println("Taking out absolute positive value out of a negative number. "+Math.abs(-12.24));
        //Random Function
        System.out.println("Random Function, this generates any random numeric value. "+Math.random());
    }
}
