public class JavaDataTypes {
    public static void main(String[] args){
        //Integer Data Type
        int num = 69;
        //Float Data Type
        float floatNum = 69.69f;
        //Character Data Type
        char text = 'D';
        //String Data Type
        String textString = "This is test line for character data type";
        //Boolean Data Type
        boolean testBool = true;

        //Printing out all the lines
        System.out.println("Integer Value: "+ num);
        System.out.println("Float Value: "+floatNum);
        System.out.println("Character value: "+text);
        System.out.println("String Value: "+textString);
        System.out.println("Boolean Value: "+testBool);

    }
}
